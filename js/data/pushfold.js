"use strict";

// Position-aware push/fold baseline for the Calc → Stack & Bubble advisor.
// Loaded as a classic script (globals on window) and importable from Node for
// tests (tests/pushfold.test.js).
//
// What this is: an APPROXIMATE chip-EV open-shove chart for a player who is
// first in (nobody has raised). Shove frequency comes from the table below,
// hands are picked from HAND_ORDER (see scripts/gen-hand-ranking.js). What it
// isn't: a solved ICM equilibrium — bubbles, pay jumps and stack distribution
// move the real answer, so treat the output as a baseline and confirm exact
// ranges in a solver (ICMIZER / HRC) when the decision is big.
(function (root) {
  var RANKS = "23456789TJQKA";

  // 169 starting-hand classes, strongest push candidates first. Generated by
  // scripts/gen-hand-ranking.js (equity vs a ~22% calling range).
  var HAND_ORDER = ["AA","KK","QQ","JJ","AKs","AKo","AQs","TT","AQo","AJs","99","AJo","88","ATs","ATo","77","A9s","66","A8s","KQs","A9o","55","44","KJs","A7s","A8o","KQo","33","A5s","A6s","22","A3s","A4s","A7o","KTs","A2s","KJo","QJs","A5o","A6o","A3o","QTs","K9s","A4o","A2o","JTs","KTo","T9s","K8s","J9s","QJo","98s","T8s","Q9s","87s","K6s","K7s","97s","76s","QTo","JTo","K9o","K5s","J8s","Q8s","86s","65s","K4s","T7s","K3s","K2s","J7s","54s","Q7s","T9o","96s","Q6s","64s","75s","85s","Q9o","98o","T6s","J9o","53s","Q3s","Q2s","87o","Q5s","43s","T8o","K8o","Q4s","K7o","74s","J4s","63s","84s","J3s","J6s","95s","J8o","94s","T4s","52s","J5s","T3s","76o","K6o","93s","J2s","T5s","T2s","97o","86o","73s","32s","Q8o","65o","T7o","92s","K5o","83s","K4o","K3o","54o","82s","42s","K2o","62s","96o","J7o","Q6o","72s","75o","64o","85o","Q7o","T6o","53o","74o","Q5o","Q4o","95o","Q3o","J6o","J4o","43o","Q2o","J5o","J2o","84o","T4o","T3o","J3o","63o","T5o","52o","T2o","42o","32o","94o","62o","73o","92o","93o","82o","83o","72o"];

  // "Behind" = players still to act after you, blinds included.
  var POSITIONS = [
    { key: "utg", label: "UTG", behind: 8 },
    { key: "utg1", label: "UTG+1", behind: 7 },
    { key: "mp", label: "Middle (MP)", behind: 6 },
    { key: "lj", label: "Lojack (LJ)", behind: 5 },
    { key: "hj", label: "Hijack (HJ)", behind: 4 },
    { key: "co", label: "Cutoff (CO)", behind: 3 },
    { key: "btn", label: "Button (BTN)", behind: 2 },
    { key: "sb", label: "Small blind (SB)", behind: 1 }
  ];

  // Approximate open-shove % of hands, no antes, by players behind and
  // effective stack in big blinds. Columns are STACKS.
  var STACKS = [3, 5, 7, 10, 12, 15, 20, 25];
  var SHOVE_PCT = {
    1: [100, 96, 80, 58, 48, 38, 28, 20],
    2: [100, 62, 48, 39, 33, 26, 19, 14],
    3: [95, 45, 34, 27, 23, 18, 13, 10],
    4: [90, 38, 28, 21, 18, 14, 10, 8],
    5: [80, 32, 24, 17, 14, 11, 8, 6.5],
    6: [70, 28, 20, 14.5, 12, 9.5, 7, 5.5],
    7: [60, 25, 18, 12.5, 10.5, 8.5, 6, 5],
    8: [55, 23, 16, 11, 9.5, 7.5, 5.5, 4.5]
  };
  var ANTE_WIDEN = 1.3;      // antes add dead money → shove wider
  var BUBBLE_TIGHTEN = 0.85; // ICM pressure near the money → shove tighter
  var MAX_STACK = STACKS[STACKS.length - 1];

  function clamp(v, lo, hi) { return Math.min(hi, Math.max(lo, v)); }

  function combosOf(name) {
    if (name.length === 2) return 6;           // pair
    return name.charAt(2) === "s" ? 4 : 12;    // suited / offsuit
  }

  // Interpolated base shove % for a stack (bb) and players-behind count.
  // Returns 0 above the deepest column: past ~25bb push/fold no longer applies.
  function basePct(stackBB, behind) {
    var row = SHOVE_PCT[clamp(Math.round(behind) || 1, 1, 8)];
    var s = Number(stackBB);
    if (!(s > 0)) return 0;
    if (s > MAX_STACK) return 0;
    if (s <= STACKS[0]) return row[0];
    for (var i = 1; i < STACKS.length; i++) {
      if (s <= STACKS[i]) {
        var t = (s - STACKS[i - 1]) / (STACKS[i] - STACKS[i - 1]);
        return row[i - 1] + (row[i] - row[i - 1]) * t;
      }
    }
    return 0;
  }

  // Final shove % after ante and bubble adjustments.
  function shovePct(opts) {
    var pct = basePct(opts.stackBB, opts.behind);
    if (opts.ante) pct *= ANTE_WIDEN;
    if (opts.bubble) pct *= BUBBLE_TIGHTEN;
    return clamp(pct, 0, 100);
  }

  // The hand classes making up the top `pct`% of combos (whole classes only).
  function rangeForPct(pct) {
    var target = (clamp(pct, 0, 100) / 100) * 1326;
    var hands = [], cum = 0;
    for (var i = 0; i < HAND_ORDER.length; i++) {
      var n = combosOf(HAND_ORDER[i]);
      if (target <= 0 || cum + n / 2 > target) break;
      hands.push(HAND_ORDER[i]);
      cum += n;
    }
    if (!hands.length && target > 0) { hands.push(HAND_ORDER[0]); cum = combosOf(HAND_ORDER[0]); }
    return { hands: hands, combos: cum, actualPct: (cum / 1326) * 100 };
  }

  function runsOf(sortedDesc) {
    var runs = [];
    sortedDesc.forEach(function (r) {
      var last = runs[runs.length - 1];
      if (last && last.bottom === r + 1) last.bottom = r;
      else runs.push({ top: r, bottom: r });
    });
    return runs;
  }

  // ["AA","KK","QQ","AKs","AQs","AKo"] → "QQ+, AQs+, AKo"
  function compressRange(names) {
    var R = RANKS;
    var pairs = [], suited = {}, offsuit = {};
    names.forEach(function (n) {
      var a = R.indexOf(n.charAt(0)), b = R.indexOf(n.charAt(1));
      if (n.length === 2) pairs.push(a);
      else {
        var map = n.charAt(2) === "s" ? suited : offsuit;
        (map[a] = map[a] || []).push(b);
      }
    });
    var out = [];
    runsOf(pairs.sort(function (x, y) { return y - x; })).forEach(function (run) {
      var hi = R.charAt(run.top) + R.charAt(run.top), lo = R.charAt(run.bottom) + R.charAt(run.bottom);
      if (run.top === 12 && run.bottom === 12) out.push("AA");
      else if (run.top === 12) out.push(lo + "+");
      else if (run.top === run.bottom) out.push(hi);
      else out.push(hi + "-" + lo);
    });
    [suited, offsuit].forEach(function (map, idx) {
      var tag = idx === 0 ? "s" : "o";
      Object.keys(map).map(Number).sort(function (x, y) { return y - x; }).forEach(function (hi) {
        runsOf(map[hi].sort(function (x, y) { return y - x; })).forEach(function (run) {
          var H = R.charAt(hi);
          if (run.top === run.bottom) out.push(H + R.charAt(run.top) + tag);
          else if (run.top === hi - 1) out.push(H + R.charAt(run.bottom) + tag + "+");
          else out.push(H + R.charAt(run.top) + tag + "-" + H + R.charAt(run.bottom) + tag);
        });
      });
    });
    return out.join(", ");
  }

  // M-ratio = stack ÷ chips paid per orbit. Without antes that's SB+BB = 1.5 BB;
  // with antes (~2.5 BB per orbit either as table antes or a big-blind ante).
  function mRatio(stackBB, ante) {
    return stackBB / (ante ? 2.5 : 1.5);
  }

  // One call for the UI: everything for the selected position plus the shove %
  // for every position at this stack so the guide can show the whole table.
  function advise(opts) {
    var stackBB = Number(opts.stackBB) || 0;
    var ante = !!opts.ante;
    var bubble = !!opts.bubble;
    var pos = POSITIONS.filter(function (p) { return p.key === opts.position; })[0] || POSITIONS[POSITIONS.length - 2];
    function forPosition(p) {
      var pct = shovePct({ stackBB: stackBB, behind: p.behind, ante: ante, bubble: bubble });
      var range = rangeForPct(pct);
      return { key: p.key, label: p.label, behind: p.behind, pct: pct, range: range, text: compressRange(range.hands) };
    }
    return {
      stackBB: stackBB,
      m: mRatio(stackBB, ante),
      applies: stackBB > 0 && stackBB <= MAX_STACK,
      selected: forPosition(pos),
      all: POSITIONS.map(forPosition)
    };
  }

  var api = {
    HAND_ORDER: HAND_ORDER,
    POSITIONS: POSITIONS,
    STACKS: STACKS,
    MAX_STACK: MAX_STACK,
    combosOf: combosOf,
    basePct: basePct,
    shovePct: shovePct,
    rangeForPct: rangeForPct,
    compressRange: compressRange,
    mRatio: mRatio,
    advise: advise
  };

  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (root && typeof root === "object") root.PokerHQPushFold = api;
})(typeof window !== "undefined" ? window : undefined);
